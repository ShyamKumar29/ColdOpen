/**
 * Guards against an alias key that isn't in canonical form, which would be
 * dead weight the matcher could never hit. Exercised by the unit tests
 * rather than at runtime.
 */
export function findNonCanonicalAliasKeys(): string[] {
  const offenders: string[] = []
  for (const [name, vocabulary] of Object.entries(vocabularies)) {
    for (const key of Object.keys(vocabulary.aliases)) {
      if (canonicalToken(key) !== key) offenders.push(`${name}.${key}`)
    }
  }
  return offenders
}

/**
 * Guards against an alias whose target isn't a member of its own
 * vocabulary — which would coerce a value straight into a second Zod
 * failure. Exercised by the unit tests.
 */
export function findUnresolvableAliasTargets(): string[] {
  const offenders: string[] = []
  for (const [name, vocabulary] of Object.entries(vocabularies)) {
    const options = vocabulary.options as readonly string[]
    for (const [key, target] of Object.entries(vocabulary.aliases)) {
      if (!options.includes(target)) offenders.push(`${name}.${key} -> ${target}`)
    }
    const fallback = (vocabulary as Vocabulary<string>).fallback
    if (fallback !== undefined && !options.includes(fallback)) {
      offenders.push(`${name}.fallback -> ${fallback}`)
    }
  }
  return offenders
}
