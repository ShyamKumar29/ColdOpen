/**
 * A closed vocabulary plus the out-of-vocabulary values that map into it.
 *
 * `options` is always read from the live Zod enum, never re-typed, so a
 * schema change can't leave a stale copy behind. `aliases` keys are
 * canonical tokens (see `canonicalToken`) — casing, spacing, and
 * punctuation variants are matched before the table is consulted, so only
 * genuinely *different words* belong here.
 *
 * Every alias must be a true synonym, a strict subtype, or the nearest
 * renderable neighbour of its target. Arbitrary substitutions (lighthouse
 * to forest, mystery to drama) are what `fallback` is for, and `fallback`
 * is deliberately the least-committal member of each vocabulary.
 */
export interface Vocabulary<T extends string> {
  readonly options: readonly T[]
  readonly aliases: Readonly<Record<string, T>>
  /**
   * Used when nothing else matches. `undefined` means the value cannot be
   * guessed: the field is either dropped (when optional) or left in place
   * for Zod to reject (when required).
   */
  readonly fallback?: T
}

